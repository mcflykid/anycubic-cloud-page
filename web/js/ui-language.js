 /** Traduit une chaîne interne du catalogue en laissant les données constructeur à leur source. */
 const text=label=>language==='fr'||!Object.hasOwn(dictionary,label)?label:dictionary[label][language==='en'?0:1];
 /** Actualise les libellés statiques au démarrage, sans changer le contenu des champs. */
 function apply(){
  document.documentElement.lang=language;
  document.title=text(document.title);
  if(language==='fr')return;
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
   const item=walker.currentNode;
   if(item.parentElement.closest('script,style,textarea'))continue;
   const label=item.textContent.trim(),translated=text(label);
   if(label&&translated!==label)item.textContent=item.textContent.replace(label,translated);
  }
  for(const element of document.querySelectorAll('[title],[aria-label],[placeholder]')){
   for(const attr of ['title','aria-label','placeholder']){
    if(element.hasAttribute(attr))element.setAttribute(attr,text(element.getAttribute(attr)));
   }
  }
 }
 function start(){
  apply();
  const choice=document.getElementById('interface-language');
  if(!choice)return;
  choice.value=language;
  choice.onchange=()=>{
   try{localStorage.setItem(localeKey,choice.value);}catch{choice.value=language;return;}
   location.reload();
  };
 }
 start();
